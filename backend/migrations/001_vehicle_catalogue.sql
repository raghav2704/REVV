CREATE TABLE IF NOT EXISTS vehicle_makes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Vehicle models linked to their manufacturer
CREATE TABLE IF NOT EXISTS vehicle_models (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    make_id INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_vehicle_models_make
        FOREIGN KEY (make_id)
        REFERENCES vehicle_makes(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_vehicle_models_make_name
        UNIQUE (make_id, name)
);

CREATE INDEX IF NOT EXISTS ix_vehicle_models_make_id
ON vehicle_models(make_id);

